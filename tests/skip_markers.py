"""Shared skip markers and constants for the topochange test suite.

Import these in individual test files:
    from tests.skip_markers import requires_pdal, requires_small_gicp, SYNTHETIC"""

import pytest


def _pdal_available() -> bool:
    # first check if the native PDAL module works
    try:
        import pdal  # noqa: F401
        return True
    except (ImportError, OSError):
        pass
    # fall back to checking the project's wrapper internals
    try:
        from topochange.pdal_wrapper import _NATIVE_PDAL_AVAILABLE, _CONDA_PDAL_AVAILABLE
        return _NATIVE_PDAL_AVAILABLE or _CONDA_PDAL_AVAILABLE
    except ImportError:
        return False


def _small_gicp_available() -> bool:
    try:
        import small_gicp  # noqa: F401
        return True
    except ImportError:
        return False


def _gdal_available() -> bool:
    try:
        from osgeo import gdal  # noqa: F401
        return True
    except ImportError:
        return False


HAS_PDAL = _pdal_available()
HAS_SMALL_GICP = _small_gicp_available()
HAS_GDAL = _gdal_available()

requires_pdal = pytest.mark.skipif(
    not HAS_PDAL, reason="PDAL is not installed"
)
requires_small_gicp = pytest.mark.skipif(
    not HAS_SMALL_GICP, reason="small_gicp is not installed"
)
requires_gdal = pytest.mark.skipif(
    not HAS_GDAL, reason="GDAL (osgeo) is not installed"
)

